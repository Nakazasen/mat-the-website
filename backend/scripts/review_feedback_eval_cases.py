import argparse
import json
import os
import sys
from typing import Any, Dict, List

# Add parent directory and backend directory to path
sys.path.append(os.path.join(os.getcwd()))
sys.path.append(os.path.join(os.getcwd(), 'backend'))

try:
    from backend.rag.eval_case_registry import build_eval_registry_summary
except ImportError:
    from rag.eval_case_registry import build_eval_registry_summary

def main():
    parser = argparse.ArgumentParser(description="Review and register feedback-derived evaluation cases.")
    parser.add_argument("--input", default="backend/rag/generated_feedback_corrections.json", help="Path to input JSON file (default: backend/rag/generated_feedback_corrections.json).")
    parser.add_argument("--output", default="backend/rag/generated_feedback_eval_cases.py", help="Path to write the python registry file (default: backend/rag/generated_feedback_eval_cases.py).")
    parser.add_argument("--json", action="store_true", help="Print summary to stdout in JSON format.")
    parser.add_argument("--write-output", default="true", help="Whether to write the output python file (default: 'true'). Can be 'true' or 'false'.")
    parser.add_argument("--dry-run", action="store_true", help="Perform verification only without writing any files (overrides --write-output).")

    args = parser.parse_args()

    # 1. Read input JSON
    if not os.path.exists(args.input):
        print(f"Error: Input file '{args.input}' not found.", file=sys.stderr)
        sys.exit(1)

    try:
        with open(args.input, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as e:
        print(f"Error reading or parsing input file '{args.input}': {e}", file=sys.stderr)
        sys.exit(1)

    raw_eval_cases = data.get("eval_cases", [])

    # 2. Augment case fields before validation
    feedback_cases = []
    for c in raw_eval_cases:
        case_copy = dict(c)
        case_copy["source"] = case_copy.get("source") or "generated_from_feedback"
        case_copy["status"] = case_copy.get("status") or "draft"
        feedback_cases.append(case_copy)

    # 3. Load baseline eval cases
    try:
        from backend.rag.eval_cases import EVAL_CASES as base_cases
    except ImportError:
        try:
            from rag.eval_cases import EVAL_CASES as base_cases
        except ImportError:
            base_cases = []

    # 4. Perform validation and checks
    summary = build_eval_registry_summary(base_cases, feedback_cases)

    # Filter valid cases for output
    valid_cases = [r["case"] for r in summary["reports"] if r["valid"]]

    # Check duplicate IDs and flag them
    has_duplicates = len(summary["duplicate_ids"]) > 0

    should_write = (args.write_output.lower() == "true") and not args.dry_run

    # 5. Write output python file if requested
    written = False
    if should_write and valid_cases:
        try:
            out_dir = os.path.dirname(args.output)
            if out_dir and not os.path.exists(out_dir):
                os.makedirs(out_dir, exist_ok=True)

            # Construct content as a clean python list definition
            content = (
                f'# Generated by review_feedback_eval_cases.py. DO NOT EDIT DIRECTLY.\n'
                f'FEEDBACK_EVAL_CASES = [\n'
            )
            for vc in valid_cases:
                content += "    {\n"
                for k, v in vc.items():
                    # Format value appropriately for Python code representation
                    content += f"        {repr(k)}: {repr(v)},\n"
                content += "    },\n"
            content += "]\n"

            with open(args.output, "w", encoding="utf-8") as f:
                f.write(content)
            written = True
        except Exception as e:
            print(f"Error writing output file '{args.output}': {e}", file=sys.stderr)
            sys.exit(1)

    # 6. Report results
    report = {
        "base_cases_count": summary["base_cases_count"],
        "feedback_cases_count": summary["feedback_cases_count"],
        "valid_count": summary["valid_count"],
        "invalid_count": summary["invalid_count"],
        "warnings_count": summary["warnings_count"],
        "duplicate_ids": summary["duplicate_ids"],
        "output_path": args.output,
        "written_to_file": written
    }

    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        print("Feedback eval cases review completed.")
        print(f" - Base cases: {report['base_cases_count']}")
        print(f" - Feedback cases: {report['feedback_cases_count']}")
        print(f" - Valid cases: {report['valid_count']}")
        print(f" - Invalid cases: {report['invalid_count']}")
        print(f" - Duplicate IDs: {len(report['duplicate_ids'])} ({', '.join(report['duplicate_ids']) if report['duplicate_ids'] else 'None'})")
        if written:
            print(f" - Generated registry written to: {args.output}")
        else:
            print(" - Local validation only (no output files written).")

if __name__ == "__main__":
    main()
